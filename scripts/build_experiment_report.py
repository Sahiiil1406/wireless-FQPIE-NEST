BLOCKS: List[tuple] = []
FIG_N = 0
TAB_N = 0
HEADINGS: List[Tuple[int, str, str]] = []


def h1(text: str) -> None:
    HEADINGS.append((1, text, slug(text)))
    BLOCKS.append(("h1", text))


def h2(text: str) -> None:
    HEADINGS.append((2, text, slug(text)))
    BLOCKS.append(("h2", text))


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s


def p(text: str) -> None:
    BLOCKS.append(("p", text))


def lead(strong: str, text: str) -> None:
    BLOCKS.append(("lead", strong, text))


def ul(items: Sequence[tuple | str]) -> None:
    BLOCKS.append(("ul", list(items)))


def note(text: str) -> None:
    BLOCKS.append(("note", text))


def code(text: str) -> None:
    BLOCKS.append(("code", text))


def kpi(items: Sequence[Tuple[str, str]]) -> None:
    BLOCKS.append(("kpi", list(items)))


def pagebreak() -> None:
    BLOCKS.append(("pagebreak",))


def figure(path: str, caption: str) -> None:
    global FIG_N
    FIG_N += 1
    BLOCKS.append(("figure", path, f"Figure {FIG_N}. {caption}"))


def table(caption: str, headers: Sequence[str], rows: Sequence[Sequence[str]],
          align: str = "numeric", widths: Sequence[float] | None = None) -> None:
    global TAB_N
