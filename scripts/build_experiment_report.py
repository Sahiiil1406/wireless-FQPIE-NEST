def load_cells() -> Dict[Tuple[str, str, int], Dict[str, object]]:
    cells: Dict[Tuple[str, str, int], Dict[str, object]] = {}
    for scenario, _ in SCENARIOS:
        for case, category in CASES:
            for target in TARGETS:
                paths = glob.glob(
                    os.path.join(
                        DATA, scenario, category, case,
                        f"target_{target}ms", "run_*", "metrics.json",
                    )
                )
                runs = [json.load(open(p)) for p in sorted(paths)]
                if not runs:
                    continue
                clean = [
                    r for r in runs
                    if float(r["link_utilization_pct"]) <= 100.5
                    and float(r["fairness_jain"]) >= 0.5
                ]
                flagged = len(clean) < 2
                use = clean if not flagged else runs
                med = {
                    key: statistics.median(float(r[key]) for r in use)
                    for key in (
                        "throughput_mbps",
                        "link_utilization_pct",
                        "packet_loss_pct",
                        "fairness_jain",
                        "queue_delay_ms",
                        "queue_delay_p95_ms",
                    )
                }
                cells[(scenario, case, target)] = {
                    **med,
                    "n_runs": len(runs),
                    "n_clean": len(clean),
                    "flagged": flagged,
                    "max_util": max(float(r["link_utilization_pct"]) for r in runs),
                }
    return cells


def latency_utility(q: float) -> float:
    if q <= 10.0:
        return 1.0
    return max(0.0, 1.0 - (q - 10.0) / 20.0)


def score(cell: Dict[str, object]) -> float:
    return (
        0.40 * min(float(cell["link_utilization_pct"]), 100.0) / 100.0
        + 0.30 * float(cell["fairness_jain"])
        + 0.20 * (1.0 - min(float(cell["packet_loss_pct"]), 20.0) / 20.0)
        + 0.10 * latency_utility(float(cell["queue_delay_ms"]))
    )


def choose_target(cells, scenario: str, case: str) -> Tuple[int, float]:
    scores = {t: score(cells[(scenario, case, t)]) for t in TARGETS}
    best = max(scores, key=lambda t: scores[t])
    gain = scores[best] - scores[15]
    return (best if gain >= 0.015 else 15), gain


CELLS = load_cells()
REC = {(s, c): choose_target(CELLS, s, c) for s, _ in SCENARIOS for c, _ in CASES}


def fmt(value: float, digits: int = 2) -> str:
    return f"{float(value):.{digits}f}"


def canonical_rows() -> List[List[str]]:
    rows = []
    for scenario, label in SCENARIOS:
        for target in TARGETS:
            c = CELLS[(scenario, "bw100mbit", target)]
            rows.append([
                label, str(target), fmt(c["throughput_mbps"], 3),
                fmt(c["link_utilization_pct"], 1), fmt(c["packet_loss_pct"], 2),
                fmt(c["fairness_jain"], 4), fmt(c["queue_delay_ms"], 2),
            ])
    return rows


def case_rows(scenario: str) -> List[List[str]]:
    rows = []
    for case, _ in CASES:
        c = CELLS[(scenario, case, 15)]
        chosen = REC[(scenario, case)][0]
        rows.append([
            case, str(chosen), fmt(c["throughput_mbps"], 3),
            fmt(c["link_utilization_pct"], 1), fmt(c["packet_loss_pct"], 2),
            fmt(c["fairness_jain"], 4), fmt(c["queue_delay_ms"], 2),
            fmt(c["queue_delay_p95_ms"], 2),
        ])
    return rows


def range_rows() -> List[List[str]]:
    rows = []
    for scenario, label in SCENARIOS:
        vals = [CELLS[(scenario, c, 15)] for c, _ in CASES]
        rows.append([
            label,
            f"{min(v['link_utilization_pct'] for v in vals):.1f}–{max(v['link_utilization_pct'] for v in vals):.1f}",
            f"{min(v['packet_loss_pct'] for v in vals):.2f}–{max(v['packet_loss_pct'] for v in vals):.2f}",
            f"{min(v['fairness_jain'] for v in vals):.3f}–{max(v['fairness_jain'] for v in vals):.3f}",
            f"{min(v['queue_delay_ms'] for v in vals):.2f}–{max(v['queue_delay_ms'] for v in vals):.2f}",
        ])
    return rows


def matrix_rows() -> List[List[str]]:
    rows = []
    for scenario, label in SCENARIOS:
        rows.append([label] + [str(REC[(scenario, c)][0]) for c, _ in CASES])
    return rows


def flag_rows() -> List[List[str]]:
    rows = []
    for scenario, label in SCENARIOS:
        for case, _ in CASES:
            for target in TARGETS:
                c = CELLS[(scenario, case, target)]
                if c["max_util"] > 100.5:
                    rows.append([
                        label, case, str(target), f"{c['max_util']:.1f}",
                        f"{c['n_clean']}/{c['n_runs']}",
                        "All runs used (flagged)" if c["flagged"] else "Clean median",
                    ])
    return rows


