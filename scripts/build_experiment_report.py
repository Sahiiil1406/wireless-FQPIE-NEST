def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    missing = []
    for block in BLOCKS:
        if block[0] == "figure":
            path = block[1]
            abs_path = os.path.join(ROOT, path) if path.startswith("wirelesss_final/") else os.path.join(OUT, path)
            if not os.path.exists(abs_path):
                missing.append(abs_path)
    if missing:
        raise SystemExit("Missing figures:\n" + "\n".join(missing))

    with open(MD_PATH, "w") as fh:
        fh.write(render_markdown())
    with open(HTML_PATH, "w") as fh:
        fh.write(render_html())
    render_docx()
    print(f"wrote {HTML_PATH}")
    print(f"wrote {MD_PATH}")
    print(f"wrote {DOCX_PATH}")
    print(f"figures embedded: {FIG_N}; tables: {TAB_N}")


if __name__ == "__main__":
    main()
