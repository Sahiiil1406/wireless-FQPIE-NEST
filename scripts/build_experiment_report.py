def inline_html(text: str) -> str:
    parts = text.split("**")
    buf = []
    for i, part in enumerate(parts):
        escaped = html.escape(part)
        escaped = re.sub(r"`([^`]+)`", r"<code>\1</code>", escaped)
        if i % 2 == 1:
            buf.append(f"<strong>{escaped}</strong>")
        else:
            buf.append(escaped)
    return "".join(buf)


