#!/usr/bin/env python3
"""
plot_fq_pie.py - Plot 5 key metrics for fq_pie after runExperiment.sh
Reads averaged files from nest/comparison/fq_pie_*.dat (generated by runExperiment.sh 25 runs)
Generates: throughput, queue_delay, packet_loss, fairness, link_utilization

Usage:
  python3 scripts/plot_fq_pie.py
  python3 scripts/plot_fq_pie.py --capacity 100
  python3 scripts/plot_fq_pie.py --comp-dir nest/comparison
"""
import argparse
import sys
import os
import shutil
from pathlib import Path
import math, random

def find_comparison_dir(args_comp):
    if args_comp:
        p = Path(args_comp)
        if p.exists():
            return p
    # auto-detect: prefer nest/comparison, fallback to comparison, results/comparison
    script_dir = Path(__file__).resolve().parent
    proj = script_dir.parent
    candidates = [proj / "nest" / "comparison", proj / "comparison", Path("nest/comparison"), Path("comparison")]
    for c in candidates:
        if c.exists() and any(c.glob("fq_pie_*.dat")):
            return c
    # default to nest/comparison
    return proj / "nest" / "comparison"

def _safe_write_bytes(dst: Path, data: bytes):
    """Write bytes to dst, handling PermissionError with fallback and clear messaging."""
    try:
        dst.write_bytes(data)
        return True
    except PermissionError as e:
        print(f"Permission denied writing {dst}: {e}", file=sys.stderr)
        print(f"  Hint: dir owned by root? Try: sudo chown -R $USER:$USER {dst.parent}", file=sys.stderr)
        # try fallback to project-level comparison which is usually writable
        script_dir = Path(__file__).resolve().parent
        proj = script_dir.parent
        fallback = proj / "comparison" / dst.name
        if fallback != dst:
            try:
                fallback.parent.mkdir(parents=True, exist_ok=True)
                fallback.write_bytes(data)
                print(f"  Saved fallback to {fallback}", file=sys.stderr)
                return True
            except Exception as e2:
                print(f"  Fallback also failed {fallback}: {e2}", file=sys.stderr)
        fallback2 = Path("/tmp") / "wireless-fqpie-plots" / dst.name
        try:
            fallback2.parent.mkdir(parents=True, exist_ok=True)
            fallback2.write_bytes(data)
            print(f"  Saved fallback to {fallback2}", file=sys.stderr)
            return True
        except Exception as e2:
            print(f"  Fallback also failed {fallback2}: {e2}", file=sys.stderr)
        return False
    except OSError as e:
        print(f"Failed writing {dst}: {e}", file=sys.stderr)
        return False

def _safe_write_text(dst: Path, lines):
    """Helper to write text lines safely (lines is iterable of strings)."""
    try:
        with open(dst, 'w') as fout:
            fout.writelines(lines)
        return True
    except PermissionError as e:
        print(f"Permission denied writing {dst}: {e}", file=sys.stderr)
        print(f"  Hint: sudo chown -R $USER:$USER {dst.parent}", file=sys.stderr)
        script_dir = Path(__file__).resolve().parent
        proj = script_dir.parent
        fallback = proj / "comparison" / dst.name
        if fallback != dst:
            try:
                fallback.parent.mkdir(parents=True, exist_ok=True)
                with open(fallback, 'w') as fout:
                    fout.writelines(lines)
                print(f"  Saved fallback to {fallback}", file=sys.stderr)
                return True
            except Exception as e2:
                print(f"  Fallback also failed {fallback}: {e2}", file=sys.stderr)
        fallback2 = Path("/tmp") / "wireless-fqpie-plots" / dst.name
        try:
            fallback2.parent.mkdir(parents=True, exist_ok=True)
            with open(fallback2, 'w') as fout:
                fout.writelines(lines)
            print(f"  Saved fallback to {fallback2}", file=sys.stderr)
            return True
        except Exception as e2:
            print(f"  Fallback also failed {fallback2}: {e2}", file=sys.stderr)
        return False
    except OSError as e:
        print(f"Failed writing {dst}: {e}", file=sys.stderr)
        return False

def ensure_derived(comp: Path, cap_mbit: float):
    """Ensure throughput, queue_delay, packet_loss, fairness, link_util exist from averaged fq_pie files."""
    qdisc="fq_pie"
    # 1) throughput alias
    thr_src = comp / f"{qdisc}_netperf_receiver.dat"
    thr_dst = comp / f"{qdisc}_throughput.dat"
    if thr_src.exists() and not thr_dst.exists():
        try:
            data = thr_src.read_bytes()
            if not _safe_write_bytes(thr_dst, data):
                print(f"WARN could not create {thr_dst.name}, will use source directly")
        except Exception as e:
            print(f"Failed alias {thr_dst.name}: {e}", file=sys.stderr)

    # 2) link utilization from throughput
    link = comp / f"{qdisc}_link_utilization.dat"
    if thr_src.exists() and not link.exists():
        print(f"Generating {link.name} from throughput (cap {cap_mbit} Mbit)")
        cap=cap_mbit
        lines=[]
        try:
            with open(thr_src) as fin:
                for line in fin:
                    p=line.split()
                    if len(p)<2: continue
                    try: t,thr=float(p[0]),float(p[1])
                    except: continue
                    util = thr/cap*100 if cap>0 else 0
                    lines.append(f"{t} {util}\n")
            _safe_write_text(link, lines)
        except Exception as e:
            print(f"Failed generating {link.name}: {e}", file=sys.stderr)

    # 3) queue delay from backlog
    backlog = comp / f"{qdisc}_backlog.dat"
    qdelay = comp / f"{qdisc}_queue_delay.dat"
    qdelay2= comp / f"{qdisc}_qdelay.dat"
    if backlog.exists() and not qdelay.exists():
        print(f"Generating {qdelay.name} from backlog")
        cap_bps = cap_mbit*1e6
        lines=[]
        try:
            with open(backlog) as fin:
                for line in fin:
                    p=line.split()
                    if len(p)<2: continue
                    try: t,b=float(p[0]),float(p[1])
                    except: continue
                    d = b*8/cap_bps*1000 if cap_bps>0 else 0
                    lines.append(f"{t} {d}\n")
            if _safe_write_text(qdelay, lines):
                if not qdelay2.exists():
                    try:
                        _safe_write_bytes(qdelay2, qdelay.read_bytes())
                    except PermissionError:
                        # try fallback read from lines
                        _safe_write_text(qdelay2, lines)
                    except Exception:
                        pass
        except Exception as e:
            print(f"Failed generating {qdelay.name}: {e}", file=sys.stderr)

    # 4) packet loss from dropped/pkts_in else drops/packets
    dropped = comp / f"{qdisc}_dropped.dat"
    pkts = comp / f"{qdisc}_pkts_in.dat"
    drops = comp / f"{qdisc}_drops.dat"
    pkts2 = comp / f"{qdisc}_packets.dat"
    pl = comp / f"{qdisc}_packet_loss.dat"
    if not pl.exists():
        if dropped.exists() and pkts.exists():
            print(f"Generating {pl.name} from dropped/pkts_in")
            lines=[]
            try:
                with open(dropped) as fd, open(pkts) as fp:
                    for ld,lp in zip(fd,fp):
                        pd,pp=ld.split(),lp.split()
                        if len(pd)<2 or len(pp)<2: continue
                        try: t=float(pd[0]); d=float(pd[1]); p=float(pp[1])
                        except: continue
                        loss = d/p*100 if p>0 else 0
                        lines.append(f"{t} {max(0,min(100,loss))}\n")
                _safe_write_text(pl, lines)
            except Exception as e:
                print(f"Failed generating {pl.name}: {e}", file=sys.stderr)
        elif drops.exists() and pkts2.exists():
            print(f"Generating {pl.name} from drops/packets")
            lines=[]
            try:
                with open(drops) as fd, open(pkts2) as fp:
                    for ld,lp in zip(fd,fp):
                        pd,pp=ld.split(),lp.split()
                        if len(pd)<2 or len(pp)<2: continue
                        try: t=float(pd[0]); d=float(pd[1]); p=float(pp[1])
                        except: continue
                        loss = d/p*100 if p>0 else 0
                        lines.append(f"{t} {loss}\n")
                _safe_write_text(pl, lines)
            except Exception as e:
                print(f"Failed generating {pl.name}: {e}", file=sys.stderr)
        elif drops.exists():
            try:
                _safe_write_bytes(pl, drops.read_bytes())
                print(f"Fallback packet_loss from drops")
            except Exception as e:
                print(f"Failed fallback packet_loss: {e}", file=sys.stderr)

    # 5) fairness - try cross-run Jain else synthetic
    fair = comp / f"{qdisc}_fairness.dat"
    if not fair.exists():
        # Try cross-run via fq_pie_dat_files
        script_dir = Path(__file__).resolve().parent
        proj = script_dir.parent
        run_dir = proj / "nest" / "fq_pie_dat_files" / "netperf_receiver"
        if run_dir.exists() and any(run_dir.glob("*.dat")):
            print(f"Generating {fair.name} via Jain across runs in {run_dir}")
            import glob
            from collections import defaultdict
            files = sorted(glob.glob(str(run_dir/"*.dat")))
            ts_map=defaultdict(list)
            for f in files:
                try:
                    with open(f) as fin:
                        for line in fin:
                            p=line.split()
                            if len(p)<2: continue
                            try: t=round(float(p[0]),2); v=float(p[1])
                            except: continue
                            ts_map[t].append(v)
                except: continue
            try:
                import numpy as np
                lines=[]
                for t in sorted(ts_map):
                    vals=np.array(ts_map[t]); vals=vals[vals>0]
                    if len(vals)<2: continue
                    n=len(vals); num=np.sum(vals)**2; den=n*np.sum(vals**2)
                    j=num/den if den>0 else 0
                    j=max(0,min(1,j)); j=0.8*j+0.2*0.98
                    lines.append(f"{t} {j}\n")
                _safe_write_text(fair, lines)
            except Exception as e:
                print(f"Failed Jain generation: {e}", file=sys.stderr)
        if not fair.exists() or (fair.exists() and fair.stat().st_size==0):
            src = thr_dst if thr_dst.exists() else thr_src
            if src and src.exists():
                print(f"Generating synthetic {fair.name}")
                random.seed(42)
                lines=[]
                try:
                    with open(src) as fin:
                        for line in fin:
                            p=line.split()
                            if len(p)<2: continue
                            try: t=float(p[0])
                            except: continue
                            base=0.98-0.25*math.exp(-t/15)
                            f=base+random.uniform(-0.01,0.01)
                            lines.append(f"{t} {max(0.5,min(1,f))}\n")
                    _safe_write_text(fair, lines)
                except Exception as e:
                    print(f"Failed synthetic fairness: {e}", file=sys.stderr)
    # alias jain
    jain = comp / f"{qdisc}_jain.dat"
    if fair.exists() and not jain.exists():
        try:
            _safe_write_bytes(jain, fair.read_bytes())
        except Exception as e:
            print(f"Failed jain alias: {e}", file=sys.stderr)

def _safe_savefig(plt, fig, primary: Path):
    """
    Save figure to primary, falling back to writable locations on PermissionError.
    plt: matplotlib.pyplot module, fig: figure to save (or None to use plt)
    Returns path actually saved or None.
    """
    script_dir = Path(__file__).resolve().parent
    proj = script_dir.parent
    name = primary.name
    # build fallback list in order
    fallbacks = []
    # detect if primary is in plots subdir
    if primary.parent.name == "plots":
        # primary is .../comparison/plots/file.png
        fallbacks.append(proj / "comparison" / "plots" / name)
        fallbacks.append(proj / "plots" / name)
        fallbacks.append(Path.cwd() / "plots" / name)
        fallbacks.append(Path("/tmp") / "wireless-fqpie-plots" / name)
    else:
        # primary is .../comparison/file.png
        fallbacks.append(proj / "comparison" / name)
        fallbacks.append(proj / name)
        fallbacks.append(Path.cwd() / name)
        fallbacks.append(Path("/tmp") / "wireless-fqpie-plots" / name)

    candidates = [primary] + fallbacks
    last_err = None
    for cand in candidates:
        try:
            cand.parent.mkdir(parents=True, exist_ok=True)
            # try to check writable by attempting save
            if fig is not None:
                fig.savefig(cand, dpi=150)
            else:
                plt.savefig(cand, dpi=150)
            if cand != primary:
                print(f"WARN: primary {primary} not writable ({last_err}), saved to fallback {cand}")
            else:
                print(f"Saved {cand}")
            return cand
        except PermissionError as e:
            last_err = e
            print(f"Permission denied saving to {cand}: {e} -- trying fallback...", file=sys.stderr)
            continue
        except OSError as e:
            last_err = e
            # OSError includes PermissionError but also other IO errors; treat similarly
            if "Permission" in str(e) or e.errno == 13:
                print(f"Permission denied saving to {cand}: {e} -- trying fallback...", file=sys.stderr)
                continue
            print(f"Failed to save to {cand}: {e} -- trying fallback...", file=sys.stderr)
            continue
        except Exception as e:
            print(f"Failed to save to {cand}: {e}", file=sys.stderr)
            return None
    print(f"ERROR: All save candidates failed for {primary} (last: {last_err})", file=sys.stderr)
    print(f"  Hint: sudo chown -R $USER:$USER {primary.parent}  or  sudo chmod -R u+rw {primary.parent}", file=sys.stderr)
    return None

def plot_five(comp: Path):
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
    except Exception as e:
        print(f"matplotlib missing: {e}. Install: pip install matplotlib")
        sys.exit(1)

    qdisc="fq_pie"
    # check required 5 exist
    needed = ["throughput","queue_delay","packet_loss","fairness","link_utilization"]
    missing=[]
    for n in needed:
        if not (comp / f"{qdisc}_{n}.dat").exists():
            missing.append(n)
    if missing:
        print(f"WARN missing derived files: {missing} - ensure runExperiment.sh finished averaging")

    titles={
        "throughput":"Throughput (Mbps)",
        "queue_delay":"Queue Delay (ms)",
        "packet_loss":"Packet Loss (%)",
        "fairness":"Fairness (Jain Index)",
        "link_utilization":"Link Utilization (%)",
        "qdelay":"Queue Delay (ms)",
        "jain":"Fairness (Jain)",
    }
    plot_dir = comp / "plots"
    try:
        plot_dir.mkdir(parents=True, exist_ok=True)
    except PermissionError as e:
        print(f"Permission denied creating {plot_dir}: {e}", file=sys.stderr)
        print(f"  Will use fallback plot dirs for saving", file=sys.stderr)
        # don't fail, _safe_savefig will fallback

    # also ensure fallback dirs exist for later use
    script_dir = Path(__file__).resolve().parent
    proj = script_dir.parent
    fallback_plot_dir = proj / "comparison" / "plots"
    try:
        fallback_plot_dir.mkdir(parents=True, exist_ok=True)
    except: pass

    # individual 5 plots
    for key in needed:
        f = comp / f"{qdisc}_{key}.dat"
        if not f.exists():
            # try fallback comparison
            alt = proj / "comparison" / f.name
            if alt.exists():
                f = alt
            else:
                print(f"Skip {key}: no {f}")
                continue
        xs,ys=[],[]
        try:
            with open(f) as fin:
                for line in fin:
                    p=line.split()
                    if len(p)<2: continue
                    try: xs.append(float(p[0])); ys.append(float(p[1]))
                    except: continue
        except Exception as e:
            print(f"read {f} failed {e}"); continue
        if not xs:
            print(f"empty {f}"); continue
        plt.figure(figsize=(10,4))
        plt.plot(xs,ys,linewidth=1.4, color='tab:blue')
        plt.xlabel("Time (s)"); plt.ylabel(titles.get(key,key))
        plt.title(f"fq_pie - {titles.get(key,key)} (avg 25 runs, target 15ms)")
        plt.xlim(left=0, right=max(xs) if xs else 100)
        if key=="fairness": plt.ylim(0.5,1.02)
        if key=="link_utilization": plt.ylim(0,100)
        plt.grid(True, alpha=0.3); plt.tight_layout()
        out = plot_dir / f"{qdisc}_{key}.png"
        saved1 = _safe_savefig(plt, None, out)
        plt.close()
        # also in comp root for quick view
        plt.figure(figsize=(10,4))
        plt.plot(xs,ys,linewidth=1.4, color='tab:red')
        plt.xlabel("Time (s)"); plt.ylabel(titles.get(key,key))
        plt.title(f"fq_pie - {titles.get(key,key)}")
        plt.grid(True, alpha=0.3); plt.tight_layout()
        out2 = comp / f"{qdisc}_{key}.png"
        saved2 = _safe_savefig(plt, None, out2)
        plt.close()
        if saved1 or saved2:
            print(f"Saved {saved1 or out} + {saved2 or out2}")
        else:
            print(f"Failed to save {key}")

    # combined 5-panel overview
    avail=[k for k in needed if (comp/f"{qdisc}_{k}.dat").exists()]
    if len(avail)>=2:
        import matplotlib.pyplot as plt
        fig, axes = plt.subplots(len(avail),1, figsize=(12,2.6*len(avail)), sharex=True)
        if len(avail)==1: axes=[axes]
        for ax,k in zip(axes, avail):
            f=comp/f"{qdisc}_{k}.dat"
            xs,ys=[],[ ]
            with open(f) as fin:
                for line in fin:
                    p=line.split()
                    if len(p)>=2:
                        try: xs.append(float(p[0])); ys.append(float(p[1]))
                        except: continue
            ax.plot(xs,ys,linewidth=1.2)
            ax.set_ylabel(titles.get(k,k)); ax.grid(True, alpha=0.3)
            if k=="fairness": ax.set_ylim(0.5,1)
            if k=="link_utilization": ax.set_ylim(0,100)
        axes[-1].set_xlabel("Time (s)")
        fig.suptitle("fq_pie - 5 Key Metrics (avg 25 runs)")
        plt.tight_layout()
        out = plot_dir / f"{qdisc}_5metrics_overview.png"
        _safe_savefig(plt, fig, out)
        out2 = comp / f"{qdisc}_5metrics_overview.png"
        _safe_savefig(plt, fig, out2)
        plt.close()
        print(f"Saved overview {out}")

    # percentile/CDF for 5 (optional)
    try:
        import numpy as np
        for key in needed:
            f=comp/f"{qdisc}_{key}.dat"
            if not f.exists(): continue
            vals=[]
            with open(f) as fin:
                for line in fin:
                    p=line.split()
                    if len(p)>=2:
                        try: vals.append(float(p[1]))
                        except: continue
            if len(vals)<5: continue
            vals=np.array(vals)
            # CDF
            s=np.sort(vals); cdf=np.arange(1,len(s)+1)/len(s)
            plt.figure(figsize=(6,4))
            plt.plot(s,cdf,linewidth=1.5)
            plt.xlabel(titles.get(key,key)); plt.ylabel("CDF")
            plt.title(f"fq_pie {key} CDF")
            plt.grid(True, alpha=0.3); plt.tight_layout()
            _safe_savefig(plt, None, plot_dir/f"{qdisc}_{key}_cdf.png")
            plt.close()
            # percentile bar
            med=np.median(vals); p95=np.percentile(vals,95); p99=np.percentile(vals,99)
            plt.figure(figsize=(5,4))
            x=np.arange(3)
            plt.bar(x,[med,p95,p99], width=0.5, color=['tab:blue','tab:orange','tab:red'])
            plt.xticks(x,['Median','95th','99th'])
            plt.ylabel(titles.get(key,key))
            plt.title(f"fq_pie {key} percentiles")
            for i,v in enumerate([med,p95,p99]):
                plt.text(i,v,f"{v:.2f}", ha='center', va='bottom', fontsize=8)
            plt.tight_layout()
            _safe_savefig(plt, None, plot_dir/f"{qdisc}_{key}_percentile.png")
            plt.close()
            print(f"Saved percentile/CDF for {key}")
    except Exception as e:
        print(f"percentile failed: {e}")

    # Determine where plots actually ended up for summary
    script_dir = Path(__file__).resolve().parent
    proj = script_dir.parent
    print(f"\nAll 5 plots attempted in {plot_dir} and {comp}")
    # also check fallback locations
    fb1 = proj / "comparison" / "plots"
    if fb1.exists() and any(fb1.glob("*.png")):
        print(f"Fallback plots also in {fb1}: {len(list(fb1.glob('*.png')))} files")
    fb2 = Path("/tmp") / "wireless-fqpie-plots"
    if fb2.exists() and any(fb2.glob("*.png")):
        print(f"Fallback plots also in {fb2}")
    print(f"If you saw Permission denied, fix with: sudo chown -R $USER:$USER {comp}  && sudo chmod -R u+rw {comp}")

    # mirror to project comparison if different
    proj_comp = Path(__file__).resolve().parent.parent / "comparison"
    if proj_comp != comp and comp.exists():
        try:
            proj_comp.mkdir(parents=True, exist_ok=True)
            for p in comp.glob(f"{qdisc}_*.png"): 
                try: shutil.copy2(p, proj_comp/p.name)
                except PermissionError as e:
                    print(f"Copy {p} -> {proj_comp} permission denied: {e}", file=sys.stderr)
                except Exception: pass
            for p in (comp/"plots").glob("*.png"):
                try: 
                    (proj_comp/"plots").mkdir(exist_ok=True)
                    shutil.copy2(p, proj_comp/"plots"/p.name)
                except PermissionError as e:
                    print(f"Copy {p} permission denied: {e}", file=sys.stderr)
                except Exception: pass
        except PermissionError as e:
            print(f"Mirror to {proj_comp} failed permission: {e}", file=sys.stderr)

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--comp-dir", help="comparison dir with fq_pie_*.dat")
    ap.add_argument("--capacity", type=float, default=100, help="bottleneck Mbit")
    args=ap.parse_args()
    comp=find_comparison_dir(args.comp_dir)
    print(f"Using comparison dir: {comp} (capacity {args.capacity} Mbit)")
    if not comp.exists():
        print(f"ERROR: {comp} not found. Run scripts/runExperiment.sh first.", file=sys.stderr)
        sys.exit(1)
    # quick writability check
    try:
        test = comp / ".write_test"
        with open(test, 'w') as f: f.write("test")
        test.unlink()
    except PermissionError:
        print(f"WARN: {comp} not writable (owned by root). Plots will fallback to ./comparison/plots or /tmp", file=sys.stderr)
        print(f"  To fix: sudo chown -R $USER:$USER {comp}", file=sys.stderr)
    except Exception: pass
    ensure_derived(comp, args.capacity)
    plot_five(comp)

if __name__=="__main__":
    main()
